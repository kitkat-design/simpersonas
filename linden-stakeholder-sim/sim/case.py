CASE_TITLE = "Linden Compute expansion decision"

CASE_FACTS = """\
THE COMPANY
Linden Compute operates two data centres. It provides secure buildings, electricity and
cooling for business customers, who install their own servers.

THE PROPOSAL
Management proposes a third site on former industrial land at the edge of Linden town.
The full development would provide 40 megawatts (MW) of capacity for customer equipment,
cost an estimated EUR 220 million and open 24 months after approval.
Management argues that one construction programme avoids the disruption of extending a
live site and creates space for customers who want capacity available before negotiating.
Several prospects have enquired, but none has signed. Waiting for contracts could reduce
exposure while giving competitors time to secure those customers.
The proposal commits to the whole development immediately. It anticipates 40 permanent
operating jobs, including 18 transfers from existing sites, and no redundancies.
Management plans an annual community meeting and a public environmental report before
construction. The estimate includes the planned site infrastructure. Training, additional
community commitments and changes to the design may require more money or time. Noise and
water assessments remain incomplete, and the grid connection and permits remain subject to
confirmation.

THE COMMERCIAL CONVERSATIONS
Clara Weiss represents a fund that owns 35 percent of Linden and holds one board seat. She
supported management through an earlier period of weak demand and has said she can accept
slow initial returns. However, she learned about a cost overrun at the previous site only
after contractors had begun work. Since then, she has asked for written downside estimates
before investment meetings. At the last briefing she left the revenue forecast aside and
asked, "What would make us stop spending?" Her recommendation matters to the fund's
willingness to provide further capital, although she cannot approve the project alone.

Daniel Hart, operations director at a major customer, has expressed interest in 10 MW at
opening and potentially another 10 MW later. He has signed no commitment. A competing
provider could supply his first requirement three months later at a higher price. Daniel
listens quietly during presentations, then sends detailed questions about delivery
milestones. He previously accepted a temporary workaround after a Linden outage because
the operations team explained the problem early and kept its promises. "I can plan around
a date I believe," he told management. "I cannot plan around a date that changes after I
have committed."

THE TOWN AND THE WORKFORCE
Mayor Miriam Keller introduced Linden to the landowner and publicly welcomed the prospect
of new employment. The municipality's cooperation matters to an access-road agreement, but
the mayor does not personally control the outstanding permits. An earlier developer
promised local apprenticeships that never materialised; residents still bring this up at
public meetings. Keller asked Linden to meet local groups before circulating designs.
Instead, a company presentation reached a local newspaper first. She has since declined a
joint press photograph, while continuing to answer the chief executive's calls.
Keller often begins meetings by asking each participant to explain what they need from the
project. She is willing to support industrial development, but wants commitments she can
defend in public. In a recent call she asked whether Linden's 40 jobs included transfers.
When told that 18 did, she requested a clearer explanation of what local applicants could
realistically expect. A general promise of "opportunities for the community" would be
difficult for her to repeat after the apprenticeship episode.

Jonas Berg chairs the residents' association, which represents households near the
proposed site. He helped negotiate delivery hours for a neighbouring factory and persuaded
members to accept an agreement once the factory published monitoring results. Some members
now want the data centre stopped, while others see a chance to improve the former
industrial site. Berg has resisted committing the association to either position. He has
no formal project veto, but can organise attendance at consultation meetings and draw
sustained public attention to unresolved issues.
At a site visit, Berg asked where residents would see noise measurements and who would
respond if limits were exceeded. He interrupted when a company manager described their
concerns as a communication problem. Later, he stayed behind to discuss monitoring
arrangements. He and Keller worked together on the factory agreement, but he has publicly
challenged her when council assurances lacked follow-through. He is prepared to consider
evidence from the company, provided someone independent can examine it.

Elena Rossi is the elected employee representative and a senior operations technician. She
helped stabilise the service after the outage Daniel remembers. She sees a new site as a
chance for colleagues to gain responsibility, and she supported the previous expansion.
Several training sessions from that project were later cancelled to cover busy shifts.
Staff still ask her whether a promise of development means learning new skills or simply
taking on more work.
The proposed transfers could create opportunities but also longer journeys and thinner
staffing at the existing sites. Rossi has asked management to show which roles move, how
training fits into paid working time and who covers the resulting gaps. She usually raises
problems privately first. When an earlier staffing concern went unanswered, she circulated
a detailed account to colleagues. She cannot authorise the investment, but the project
needs employees willing and prepared to operate the site.

BEFORE THE STAKEHOLDER MEETING
The executive team has invited Weiss, Hart, Keller, Berg and Rossi to discuss the proposal.
Their relationships may matter: Hart remembers Rossi's work during the outage, Keller and
Berg share a history of negotiation, and Weiss is asking management whether public
commitments could create costs missing from the investment estimate.
The case supplies no quantified return forecast, completed impact study or costed
alternative design. These are open questions. Agreement in the meeting would still leave
formal approvals and technical feasibility to establish.
"""

